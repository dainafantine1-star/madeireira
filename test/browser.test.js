import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, rmSync,writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { createServer } from 'node:net';
import { settings, root } from '../server/db.js';
import { openDatabase } from '../test/fixtures/database.js';
import { createApp } from '../server/index.js';

const edge=process.env.EDGE_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const delay=ms=>new Promise(r=>setTimeout(r,ms));
test('browser: storefront, hostile content, cart recovery, storage failure, WhatsApp and API outage', {skip:!existsSync(edge),timeout:60000}, async(t)=>{
  const db=openDatabase(':memory:');
  db.prepare('UPDATE company_settings SET public_json=?').run(JSON.stringify({...settings(db),whatsapp:'5571999998888',confirmed:true}));
  db.prepare('UPDATE products SET name=?,image=?,price_cents=NULL,old_price_cents=NULL WHERE id=1').run('Porta " onerror="window.injected=true <b>Teste</b>','https://example.invalid/image.jpg');
  const app=createApp({db});app.listen(0,'127.0.0.1');await once(app,'listening');
  const origin=`http://127.0.0.1:${app.address().port}`;
  const portFinder=createServer();portFinder.listen(0,'127.0.0.1');await once(portFinder,'listening');const debugPort=portFinder.address().port;await new Promise(r=>portFinder.close(r));
  const profile=mkdtempSync(join(tmpdir(),'mp-edge-'));
  const browser=spawn(edge,['--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check',`--remote-debugging-port=${debugPort}`,`--user-data-dir=${profile}`,'about:blank'],{windowsHide:true,stdio:'ignore'});
  let ws;
  t.after(async()=>{
    ws?.close();browser.kill();app.closeAllConnections();await new Promise(r=>app.close(r));db.close();
    await delay(700);
    assert.equal(resolve(dirname(profile)),resolve(tmpdir()));
    for(let n=0;n<5;n++) {try {rmSync(profile,{recursive:true,force:true});break;} catch {await delay(300);}}
  });
  let pages;
  for(let n=0;n<80;n++){try{pages=await (await fetch(`http://127.0.0.1:${debugPort}/json/list`)).json();if(pages.some(p=>p.type==='page'))break;}catch{} await delay(150);}
  assert.ok(pages?.some(p=>p.type==='page'),'Headless browser started');
  ws=new WebSocket(pages.find(p=>p.type==='page').webSocketDebuggerUrl);await once(ws,'open');
  let serial=0;const pending=new Map();
  ws.addEventListener('message',e=>{const message=JSON.parse(e.data);if(message.id){const task=pending.get(message.id);pending.delete(message.id);if(message.error)task.reject(new Error(message.error.message));else task.resolve(message.result);}});
  const command=(method,params={})=>new Promise((resolve,reject)=>{const id=++serial;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
  const evaluate=async(expression)=>{const result=await command('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});assert.equal(result.exceptionDetails,undefined,JSON.stringify(result.exceptionDetails));return result.result.value;};
  const waitFor=async(expression)=>{for(let n=0;n<100;n++){if(await evaluate(expression))return;await delay(100);}assert.fail(`Timed out: ${expression}\n${await evaluate('location.href+"\\n"+document.body.innerText')}`);};
  await command('Page.enable');await command('Page.navigate',{url:origin});
  await waitFor('document.querySelectorAll(".product").length===10');
  assert.equal(await evaluate('window.injected'),undefined);
  assert.equal(await evaluate('document.querySelector(".product__name").textContent'),'Porta " onerror="window.injected=true <b>Teste</b>');
  assert.equal(await evaluate('document.querySelector(".product__price").textContent'),'Sob consulta');
  assert.equal(await evaluate('document.querySelector("[onerror]")'),null);
  await evaluate('localStorage.setItem("mp_cart_v1",JSON.stringify([{id:1,qty:-1},{id:2,qty:2},{id:999,qty:3},{id:1,qty:"4"}]));location.reload()');
  await waitFor('document.querySelectorAll(".product").length===10');
  assert.equal(await evaluate('document.getElementById("cartBadge").textContent'),'2');
  await evaluate(`document.querySelector('#productsGrid .product[data-id="1"] .product__media').click()`);
  await waitFor(`document.getElementById('productOrderForm')!==null`);
  assert.match(await evaluate('location.pathname'),/^\/produto\/1\//);
  await evaluate(`document.getElementById('productAdd').click()`);
  assert.match(await evaluate('document.getElementById("cartTotal").textContent'),/itens sob consulta/);
  await evaluate('window.confirm=()=>false;document.getElementById("clearCart").click()');
  assert.equal(await evaluate('document.getElementById("cartBadge").textContent'),'3');
  await evaluate('window.confirm=()=>true;document.getElementById("clearCart").click()');
  assert.equal(await evaluate('document.getElementById("cartBadge").textContent'),'0');
  await evaluate(`Storage.prototype.setItem=function(){throw new DOMException('Blocked','QuotaExceededError')};document.getElementById('productAdd').click()`);
  assert.equal(await evaluate('document.getElementById("cartBadge").textContent'),'1');
  assert.equal(await evaluate('document.getElementById("cartStorageStatus").hidden'),false);
  assert.match(await evaluate('document.getElementById("cartStorageStatus").textContent'),/Não foi possível salvar/);
  assert.equal(await evaluate('document.querySelector(".pdp-price strong").textContent'),'Sob consulta');
  assert.equal(await evaluate('document.querySelector("#productPage h1").querySelector("b")'),null);
  await evaluate(`document.getElementById('cartClose').click();document.getElementById('productRequest').click()`);
  await waitFor(`document.getElementById('quoteDialog').open`);
  await evaluate(`const form=document.getElementById('quoteForm');form.elements.name.value='Cliente navegador';form.elements.phone.value='71988887777';form.requestSubmit()`);
  await waitFor(`!document.getElementById('quoteSuccess').hidden`);
  const url=await evaluate(`document.getElementById('quoteWhats').href`);assert.ok(url.startsWith('https://wa.me/5571999998888?text='));
  const message=new URL(url).searchParams.get('text');assert.match(message,/Referência: MP-0001/);assert.match(message,/Total: Sob consulta/);assert.doesNotMatch(message,/R\$\s*0,00/);
  assert.equal(db.prepare('SELECT count(*) AS n FROM orders').get().n,1);
  assert.match(await evaluate(`document.getElementById('quoteProtocol').textContent`),/^MP-/);
  await evaluate(`document.getElementById('quoteDone').click()`);
  assert.equal(await evaluate('document.getElementById("cartBadge").textContent'),'1');
  // Hide the API from the browser to check the actual error/retry UI.
  await command('Network.enable');await command('Network.setBlockedURLs',{urls:['*api/catalog*']});await command('Page.reload');
  await waitFor('document.getElementById("retryCatalog") && !document.getElementById("retryCatalog").hidden');
  assert.equal(await evaluate('document.getElementById("checkoutBtn").disabled'),true);
  assert.match(await evaluate('document.getElementById("catalogStatus").textContent'),/indisponível/);
  await command('Network.setBlockedURLs',{urls:[]});await evaluate('document.getElementById("retryCatalog").click()');await waitFor('document.querySelectorAll(".product").length===10');
  assert.equal(await evaluate('document.getElementById("catalogStatus").textContent'),'');
  await command('Page.navigate',{url:origin});await waitFor('document.querySelectorAll(".product").length===10');
  await evaluate(`const search=document.getElementById('searchInput');search.value='MP 0001';search.dispatchEvent(new Event('input'))`);
  assert.equal(await evaluate(`document.querySelectorAll('#productsGrid .product').length`),1);
  await evaluate(`document.getElementById('searchInput').value='80 x 210 cm';document.getElementById('searchInput').dispatchEvent(new Event('input'))`);
  assert.equal(await evaluate(`document.querySelectorAll('#productsGrid .product').length`),1);
  db.prepare("UPDATE products SET name='Porta de Madeira Maciça',featured=1,status='promotion',price_cents=89000,old_price_cents=95000 WHERE id=1").run();
  await command('Page.reload');await waitFor(`document.querySelectorAll('#productsGrid .product').length===10 && !document.getElementById('destaques').hidden`);
  await command('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await command('Page.captureScreenshot',{format:'png',captureBeyondViewport:false}).then(r=>writeFileSync(join(root,'screenshot-storefront-desktop.png'),Buffer.from(r.data,'base64')));
  await evaluate(`document.querySelector('.desktop-nav [data-mode="promotions"]').click()`);
  assert.equal(await evaluate(`document.querySelectorAll('#productsGrid .product').length`),1);
  await command('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  assert.equal(await evaluate(`document.documentElement.scrollWidth<=innerWidth+1`),true);
  assert.equal(await evaluate(`(()=>{const wa=document.getElementById('waFloat').getBoundingClientRect();const nav=document.querySelector('.mobile-nav').getBoundingClientRect();return wa.bottom<=nav.top})()`),true);
  await evaluate(`window.scrollTo(0,0)`);
  await command('Page.captureScreenshot',{format:'png',captureBeyondViewport:false}).then(r=>writeFileSync(join(root,'screenshot-storefront-mobile.png'),Buffer.from(r.data,'base64')));
});
