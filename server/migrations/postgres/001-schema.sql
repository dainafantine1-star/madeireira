-- Schema dedicado da loja, isolado do projeto legado que já ocupa o schema public.
CREATE SCHEMA IF NOT EXISTS loja;

-- Schema do Postgres (Supabase).
-- Gerado a partir do schema SQLite em uso, mantendo os mesmos nomes de tabela,
-- coluna e índice para que as queries da aplicação não mudem.
-- Timestamps seguem como texto ISO (to_char UTC) porque a aplicação compara
-- essas colunas como strings: 'YYYY-MM-DD HH:MM:SS' ordena corretamente.

-- Funções equivalentes às do SQLite usadas pela aplicação.
CREATE OR REPLACE FUNCTION loja.sqlite_date(value text) RETURNS text AS $$ SELECT to_char(NULLIF(value,'')::timestamptz, 'YYYY-MM-DD') $$ LANGUAGE sql IMMUTABLE;
CREATE OR REPLACE FUNCTION loja.public_json_extract(json_text text, path text) RETURNS text AS $$ SELECT (json_text::jsonb #>> string_to_array(replace(path,'$.',''),'.')) $$ LANGUAGE sql IMMUTABLE;


CREATE TABLE loja.admin_users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'admin',
  active integer NOT NULL DEFAULT 1,
  created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
  is_owner integer NOT NULL DEFAULT 0
);

CREATE TABLE loja.admin_sessions (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL,
  expires_at bigint NOT NULL,
  CONSTRAINT fk_admin_sessions_user_id FOREIGN KEY (user_id) REFERENCES loja.admin_users(id)
);

